    public Task SyncCloudNowAsync()
    {
        if (!_storageReady)
        {
            return Task.CompletedTask;
        }

        if (!_preferences.ClipboardCloudSyncEnabled)
        {
            CloudSyncStatus = "请先在设置中保存坚果云凭据并启用同步。";
            return Task.CompletedTask;
        }

        CloudSyncStatus = "正在加密同步剪贴板…";
        return _cloudSync.SyncNowAsync(SnapshotItemsForSync(), ApplyCloudSyncResult);
    }

    public void Dispose()
    {
        if (_disposed) { return; }
        _disposed = true;
        _isShuttingDown = true;
        _monitor.Changed -= OnClipboardChanged;
        _preferences.PropertyChanged -= _preferenceChanged;
        _cloudSync.Dispose();
        _filterDebouncer.Cancel();
        _persistence.Dispose();
    }

    public async Task FlushPendingChangesAsync()
    {
        _isShuttingDown = true;
        _monitor.Changed -= OnClipboardChanged;
        _preferences.PropertyChanged -= _preferenceChanged;
        _cloudSync.StopPeriodicPull();
        _filterDebouncer.Cancel();
        // Capture completions can schedule a save. Keep the Dispatcher alive
        // and drain local work until every follow-up and outbox save is done.
        while (_localWork.Count > 0)
        {
            var batch = _localWork.ToArray();
            try { await Task.WhenAll(batch); }
            catch (Exception exception) { StorageError = $"剪贴板后台保存失败：{exception.Message}"; }
            _localWork.ExceptWith(batch);
        }
    }

    private void TrackLocalWork(Task work)
    {
        _localWork.Add(work);
        _ = ObserveLocalWorkAsync(work);
    }

    private async Task ObserveLocalWorkAsync(Task work)
    {
        try { await work; }
        catch (Exception exception) { StorageError = $"剪贴板后台保存失败：{exception.Message}"; }
        finally { _localWork.Remove(work); }
    }

    public void LoadMore()
    {
        if (!HasMore) { return; }
        _visibleLimit += PageSize;
        RebuildFilteredItems();
    }

    public void PrepareForPresentation()
    {
        _visibleLimit = PageSize;
        Query = "";
        Filter = ClipboardFilter.All;
        SelectedIndex = 0;
        // When Query/Filter were already at their defaults the setters above are
        // no-ops, so force one synchronous rebuild to pick up items captured or
        // loaded since the last presentation.
        _filterDebouncer.Cancel();
        RebuildFilteredItems();
        PollPasteboard();
    }

    public bool ClearQuery()
    {
        if (string.IsNullOrEmpty(Query))
        {
            return false;
        }

        Query = "";
        return true;
    }

    public void MoveSelection(int offset)
    {
        EnsureFilterIsCurrent();
        var visible = _filteredItems;
        if (visible.Count == 0)
        {
            return;
        }

        SelectedIndex = (SelectedIndex + offset + visible.Count) % visible.Count;
    }

    public async Task<bool> CopySelectedAsync()
    {
        EnsureFilterIsCurrent();
        if (!_filteredItems.Any() || !_filteredItems.Indices().Contains(SelectedIndex))
        {
            return false;
        }

        return await CopyAsync(_filteredItems[SelectedIndex]);
    }

    public async Task<bool> CopyAsync(ClipboardHistoryItem item)
    {
        if (IsCopying || _isShuttingDown) { return false; }
        IsCopying = true;
        CopyError = null;
        try
        {
            if (!await WriteToSystemClipboard(item))
            {
                CopyError = "无法读取原件或写入系统剪贴板，请稍后重试。";
                return false;
            }
            if (_isShuttingDown) { return false; }
            PromoteToTop(item);
            return true;
        }
        catch (Exception exception) { CopyError = $"复制失败：{exception.Message}"; return false; }
        finally { IsCopying = false; }
    }

    private async Task<bool> WriteToSystemClipboard(ClipboardHistoryItem item)
    {
        switch (item.Kind)
        {
            case ClipboardItemKind.Text:
                return TrySetClipboard(() => Clipboard.SetText(item.Payload.FirstOrDefault() ?? ""));
            case ClipboardItemKind.Files:
                var collection = new System.Collections.Specialized.StringCollection();
                collection.AddRange(item.Payload.ToArray());
                return TrySetClipboard(() => Clipboard.SetFileDropList(collection));
            case ClipboardItemKind.Image:
                var data = await ResolveOriginalImageData(item);
                return data is not null && TrySetClipboard(() => Clipboard.SetImage(DecodeImage(data)));
            default:
                return false;
        }
    }

    /// <summary>
    /// Re-copying a history entry makes it the newest entry: CreatedAt drives
    /// both the visible ordering and retention, and UpdatedAt propagates the
    /// recency to other devices through the cloud LWW merge.
    /// </summary>
    private void PromoteToTop(ClipboardHistoryItem item)
    {
        var index = _items.FindIndex(existing => existing.Id == item.Id);
        if (index < 0)
        {
            return;
        }

        var timestamp = DateTimeOffset.UtcNow;
        var promoted = _items[index] with { CreatedAt = timestamp, UpdatedAt = timestamp };
        _items.RemoveAt(index);
        _items.Insert(0, promoted);
        SortItems();
        RebuildFilteredItems();
        PersistCurrent(changedItem: promoted);
    }

    /// <summary>Full-size image bytes: vault record first, in-memory copy as fallback.</summary>
    private async Task<byte[]?> ResolveOriginalImageData(ClipboardHistoryItem item)
    {
        if (_imageTasks.TryGetValue(item.Id, out var cached))
        {
            var cachedData = await cached;
            if (cachedData is { Length: > 0 })
            {
                return cachedData;
            }
        }

        var load = _persistence.ImageDataAsync(item.Id);
        _imageTasks[item.Id] = load;
        TrimImageTasks();
        var data = await load;
        if (data is not { Length: > 0 })
        {
            // Never cache a failed load: after persistence completes the vault
            // can serve the original even though it could not just now.
            _imageTasks.Remove(item.Id);
            return null;
        }

        return data;
    }

    private void TrimImageTasks()
    {
        if (_imageTasks.Count <= 64)
        {
            return;
        }

        foreach (var id in _imageTasks
                     .Where(pair => pair.Value.IsCompleted)
                     .Select(pair => pair.Key)
                     .Take(_imageTasks.Count - 32)
                     .ToList())
        {
            _imageTasks.Remove(id);
        }
    }

    public void Delete(ClipboardHistoryItem item)
    {
        if (IsClearing) { return; }
        _items.RemoveAll(existing => existing.Id == item.Id);
        SelectedIndex = Math.Min(SelectedIndex, Math.Max(_filteredItems.Count - 1, 0));
        RebuildFilteredItems();
        PersistCurrent(deletedIds: [item.Id]);
    }

    public void DeleteSelected()
    {
        EnsureFilterIsCurrent();
        if (!_filteredItems.Any() || !_filteredItems.Indices().Contains(SelectedIndex))
        {
            return;
        }

        Delete(_filteredItems[SelectedIndex]);
    }

    public void TogglePinned(ClipboardHistoryItem item)
    {
        if (IsClearing) { return; }
        var index = _items.FindIndex(existing => existing.Id == item.Id);
        if (index < 0)
        {
            return;
        }

        _items[index] = item with { IsPinned = !item.IsPinned, UpdatedAt = DateTimeOffset.UtcNow };
        SortItems();
        RebuildFilteredItems();
        PersistCurrent(changedItem: _items.First(existing => existing.Id == item.Id));
    }

    public string? SelectedText
    {
        get
        {
            EnsureFilterIsCurrent();
            if (!_filteredItems.Any()
                || !_filteredItems.Indices().Contains(SelectedIndex)
                || _filteredItems[SelectedIndex].Kind != ClipboardItemKind.Text)
            {
                return null;
            }

            return _filteredItems[SelectedIndex].Payload.FirstOrDefault();
        }
    }

    public void Clear()
    {
        if (!_storageReady || IsClearing) { return; }
        IsClearing = true;
        var previous = _items;
        var deletedAt = DateTimeOffset.UtcNow;
        foreach (var item in previous) { _localDeletedForSync[item.Id] = deletedAt; }
        _items = [];
        SelectedIndex = 0;
        _persistenceRevision += 1;
        var revision = _persistenceRevision;
        _persistenceWritable = false;
        RebuildFilteredItems();
        TrackLocalWork(ClearAsync(previous, previous.Select(item => item.Id).ToList(), revision, deletedAt, CloudConfiguration));
    }

    public void ClearRecent(int minutes)
    {
        if (IsClearing) { return; }
        var cutoff = DateTimeOffset.UtcNow.AddMinutes(-minutes);
        var removed = _items.Where(item => item.CreatedAt >= cutoff).Select(item => item.Id).ToList();
        _items.RemoveAll(item => removed.Contains(item.Id));
        SelectedIndex = Math.Min(SelectedIndex, Math.Max(_filteredItems.Count - 1, 0));
        RebuildFilteredItems();
        PersistCurrent(deletedIds: removed);
    }

    private async Task ClearAsync(List<ClipboardHistoryItem> previous, IReadOnlyList<Guid> deletedIds, int revision,
        DateTimeOffset deletedAt, ClipboardCloudSyncService.Configuration configuration)
    {
        try { await ClearAndEnqueueAsync(previous, deletedIds, revision, deletedAt, configuration); }
        finally { IsClearing = false; }
    }

    private async Task ClearAndEnqueueAsync(List<ClipboardHistoryItem> previous, IReadOnlyList<Guid> deletedIds, int revision,
        DateTimeOffset deletedAt, ClipboardCloudSyncService.Configuration configuration)
    {
        var (success, error) = await _persistence.ClearAsync(revision);
        if (!success)
        {
            if (revision != _persistenceRevision) { return; }
            _items = previous;
            _persistenceWritable = false;
            StorageError = $"无法清除剪贴板密文：{error}";
            RebuildFilteredItems();
            return;
        }

        if (revision == _persistenceRevision)
        {
            _persistenceWritable = true;
            StorageError = null;
            StorageByteCount = 0;
            if (_items.Count > 0) { PersistCurrent(); }
        }
        await HandleEnqueueResultAsync(await _cloudSync.EnqueueDeletedAsync(deletedIds, deletedAt, configuration));
    }

    private async Task LoadAsync()
    {
        var result = await _persistence.LoadAsync();
        var byteCount = await _persistence.DiskUsageAsync();
        switch (result.Kind)
        {
            case ClipboardStoreLoadResultKind.Missing:
                _items = [];
                StorageError = null;
                _persistenceWritable = true;
                break;
            case ClipboardStoreLoadResultKind.Loaded:
                _items = result.Items!.Where(item => item.Kind != ClipboardItemKind.Files
                    || item.Payload.All(path => File.Exists(path) || Directory.Exists(path))).ToList();
                StorageError = result.Warning;
                _persistenceWritable = true;
                break;
            default:
                _items = [];
                StorageError = $"{result.Warning} 新记录仅保留在本次运行内存中。";
                _persistenceWritable = false;
                break;
        }

        StorageByteCount = byteCount;
        _storageReady = true;
        IsLoading = false;
        Prune();
        RebuildFilteredItems();
        if (_persistenceWritable)
        {
            PersistCurrent();
        }

        await _cloudSync.InitializeAsync();
        RaisePropertyChanged(nameof(HasCloudSyncCredentials));
        StartCloudSync();
    }

    private void OnClipboardChanged()
    {
        PollPasteboard();
    }

    private void PollPasteboard()
    {
        if (!_storageReady || _isShuttingDown)
        {
            return;
        }

        if (!_preferences.ClipboardEnabled || _preferences.ClipboardPaused)
        {
            return;
        }

        ClipboardCapture? capture;
        try
        {
            capture = MakeCapture();
        }
        catch
        {
            // Clipboard contention is transient; wait for the next change event.
            return;
        }

        if (capture is null)
        {
            return;
        }

        TrackLocalWork(Task.Run(() => ProcessCapture(capture))
            .ContinueWith(task =>
            {
                if (task.IsCompletedSuccessfully && task.Result is { } processed)
                {
                    Ingest(processed);
                }
            }, TaskScheduler.FromCurrentSynchronizationContext()));
    }

    private ClipboardCapture? MakeCapture()
    {
        var source = ForegroundProcessName();
        var createdAt = DateTimeOffset.UtcNow;
        var data = Clipboard.GetDataObject();
        if (IsSensitive(data, source))
        {
            return null;
        }

        if (Clipboard.ContainsFileDropList())
        {
            var paths = Clipboard.GetFileDropList().Cast<string>().Take(20).ToList();
            return paths.Count == 0 ? null : ClipboardCapture.Files(paths, source, createdAt);
        }

        if (_preferences.ClipboardStoreImages && Clipboard.ContainsImage())
        {
            try
            {
                var image = Clipboard.GetImage();
                if (image is not null)
                {
                    // Copy the pixels into a frozen bitmap now; PNG encoding is
                    // too slow for the UI thread and runs in ProcessCapture.
                    var standalone = new FormatConvertedBitmap(image, System.Windows.Media.PixelFormats.Pbgra32, null, 0);
                    standalone.Freeze();
                    return ClipboardCapture.Image(standalone, source, createdAt);
                }
            }
            catch
            {
                // Clipboard image formats vary; fall through to text.
            }
        }

        if (Clipboard.ContainsText())
        {
            var text = Clipboard.GetText();
            var policy = new ClipboardTextPolicy(_preferences.ClipboardMaximumTextCharacters);
            return policy.ShouldStore(text) ? ClipboardCapture.Text(text, source, createdAt) : null;
        }

        return null;
    }

    private bool IsSensitive(System.Windows.IDataObject? data, string? sourceProcess)
    {
        if (data is not null)
        {
            foreach (var format in SensitiveFormats)
            {
                if (data.GetDataPresent(format, autoConvert: false))
                {
                    return true;
                }
            }
        }

        var processName = sourceProcess?.ToLowerInvariant() ?? "";
        if (_preferences.ClipboardIgnoredProcessNames.Contains(processName))
        {
            return true;
        }

        return DefaultIgnoredProcesses.Contains(processName);
    }

    private static ProcessedClipboardCapture? ProcessCapture(ClipboardCapture capture)
    {
        const int maximumTextBytes = 1_000_000;
        const int maximumImageBytes = 5_000_000;
        switch (capture.Kind)
        {
            case ClipboardCaptureKind.Files:
                return capture.Paths is { Count: 0 } || capture.Paths is null
                    ? null
                    : new ProcessedClipboardCapture(
                        new ClipboardHistoryItem(
                            Guid.NewGuid(),
                            ClipboardItemKind.Files,
                            capture.Paths,
                            capture.CreatedAt,
                            capture.SourceApplication,
                            ContentHash: Hash(capture.Paths)),
                        null);
            case ClipboardCaptureKind.Text:
                if (capture.Value is null
                    || string.IsNullOrWhiteSpace(capture.Value)
                    || Encoding.UTF8.GetByteCount(capture.Value) > maximumTextBytes)
                {
                    return null;
                }

                return new ProcessedClipboardCapture(
                    new ClipboardHistoryItem(
                        Guid.NewGuid(),
                        ClipboardItemKind.Text,
                        [capture.Value],
                        capture.CreatedAt,
                        capture.SourceApplication,
                        ContentHash: Hash([capture.Value])),
                    null);
            case ClipboardCaptureKind.Image:
                if (capture.ImageSource is null)
                {
                    return null;
                }

                var png = EncodePng(capture.ImageSource);
                if (png is null || png.Length > maximumImageBytes)
                {
                    return null;
                }

                var item = new ClipboardHistoryItem(
                    Guid.NewGuid(),
                    ClipboardItemKind.Image,
                    [$"图片 · {capture.ImageSource.PixelWidth} × {capture.ImageSource.PixelHeight}"],
                    capture.CreatedAt,
                    capture.SourceApplication,
                    ContentHash: Hash(png));
                return new ProcessedClipboardCapture(item, png);
            default:
                return null;
        }
    }

    private void Ingest(ProcessedClipboardCapture processed)
    {
        var duplicate = _items.FindIndex(item => item.HasSameContent(processed.Item));
        if (duplicate >= 0)
        {
            var existing = _items[duplicate];
            _items[duplicate] = existing with { CopyCount = existing.CopyCount + 1 };
            SortItems();
            RebuildFilteredItems();
            PersistCurrent();
            return;
        }

        _items.Insert(0, processed.Item);
        SortItems();
        Prune();
        RebuildFilteredItems();
        var images = processed.OriginalImage is null
            ? new Dictionary<Guid, byte[]>()
            : new Dictionary<Guid, byte[]> { [processed.Item.Id] = processed.OriginalImage };
        PersistCurrent(images, changedItem: processed.Item);
    }

    private void PruneAndPersist()
    {
        if (!_storageReady)
        {
            return;
        }

        Prune();
        PersistCurrent();
    }

    private void Prune()
    {
        var cutoff = DateTimeOffset.UtcNow.AddDays(-_preferences.ClipboardRetentionDays);
        _items = _items
            .Where(item => item.IsPinned || item.CreatedAt >= cutoff)
            .Take(_preferences.ClipboardMaximumItems)
            .ToList();
        SelectedIndex = Math.Min(SelectedIndex, Math.Max(_filteredItems.Count - 1, 0));
    }

    private void SortItems()
    {
        _items = _items
            .OrderByDescending(item => item.IsPinned)
            .ThenByDescending(item => item.CreatedAt)
            .ToList();
    }

    private void PersistCurrent(
        IReadOnlyDictionary<Guid, byte[]>? originalImages = null,
        ClipboardHistoryItem? changedItem = null,
        IReadOnlyList<Guid>? deletedIds = null,
        ClipboardCloudBatch? acknowledge = null)
    {
        if (!_storageReady || !_persistenceWritable)
        {
            return;
        }

        var deletedAt = DateTimeOffset.UtcNow;
        if (deletedIds is not null) { foreach (var id in deletedIds) { _localDeletedForSync[id] = deletedAt; } }
        _persistenceRevision += 1;
        var revision = _persistenceRevision;
        var snapshot = _items.ToList();
        var images = originalImages ?? new Dictionary<Guid, byte[]>();
        TrackLocalWork(HandlePersistCompletion(_persistence.PersistAsync(snapshot, images, revision),
            revision, changedItem, deletedIds, deletedAt, acknowledge, images, CloudConfiguration));
    }

    private async Task HandlePersistCompletion(
        Task<(bool Success, List<ClipboardHistoryItem>? Normalized, string? Error)> task,
        int revision,
        ClipboardHistoryItem? changedItem,
        IReadOnlyList<Guid>? deletedIds,
        DateTimeOffset deletedAt,
        ClipboardCloudBatch? acknowledge,
        IReadOnlyDictionary<Guid, byte[]> originalImages,
        ClipboardCloudSyncService.Configuration configuration)
    {
        try
        {
            var (success, normalized, error) = await task;
            if (!success)
            {
                if (revision != _persistenceRevision) { return; }
                _persistenceWritable = false;
                StorageError = $"剪贴板加密存储失败；后续修改仅保留在本次运行内存中：{error}";
                return;
            }

            var byteCount = await _persistence.DiskUsageAsync();
            if (revision == _persistenceRevision)
            {
                if (normalized is not null) { _items = normalized; }
                StorageByteCount = byteCount;
                StorageError = null;
                RebuildFilteredItems();
            }
            if (acknowledge is not null) { await _cloudSync.AcknowledgeAsync(acknowledge); }
            // Every successfully persisted mutation is published even when its
            // UI snapshot was superseded by a newer local revision.
            if (changedItem is not null)
            {
                var itemToPublish = normalized?.FirstOrDefault(item => item.Id == changedItem.Id) ?? changedItem;
                await EnqueueChangedItemAsync(itemToPublish, originalImages.GetValueOrDefault(itemToPublish.Id), configuration);
            }
            else if (deletedIds is { Count: > 0 })
            {
                await HandleEnqueueResultAsync(await _cloudSync.EnqueueDeletedAsync(deletedIds, deletedAt, configuration));
            }
        }
        catch (Exception exception)
        {
            CloudSyncStatus = $"同步待重试：{exception.Message}";
        }
    }

    private void StartCloudSync()
    {
        if (_isShuttingDown) { return; }
        _cloudSync.StartPeriodicPull(SnapshotItemsForSync, ApplyCloudSyncResult);
        if (_preferences.ClipboardCloudSyncEnabled && _cloudSync.PendingBatch is { } batch)
        { ApplyCloudSyncResult(ClipboardCloudSyncResult.Succeeded(null, "正在恢复已接收的剪贴板变更…") with { Batch = batch }); }
    }

    /// <summary>
    /// The pull timer fires on a thread-pool thread; enumerate _items on the
    /// UI thread it belongs to instead.
    /// </summary>
    private IReadOnlyList<ClipboardHistoryItem> SnapshotItemsForSync()
    {
        return _dispatcher.CheckAccess()
            ? _items.ToList()
            : _dispatcher.Invoke(() => _items.ToList());
    }

    private async Task EnqueueChangedItemAsync(ClipboardHistoryItem item, byte[]? originalImage,
        ClipboardCloudSyncService.Configuration configuration)
    {
        if (item.Kind != ClipboardItemKind.Image)
        {
            await HandleEnqueueResultAsync(await _cloudSync.EnqueueChangedItemAsync(item, configuration));
            return;
        }

        // item.BinaryData is normally the 192px thumbnail. Upload the original
        // when the vault can serve it; otherwise publish without image bytes so
        // receivers keep the copy they already hold for this ContentHash.
        byte[]? fullImage = null;
        try
        {
            fullImage = originalImage ?? await _persistence.ImageDataAsync(item.Id);
        }
        catch
        {
            // Fall through and publish without image bytes.
        }

        var publishable = fullImage is { Length: > 0 }
            ? item with { BinaryData = fullImage }
            : item with { BinaryData = null };
        await HandleEnqueueResultAsync(await _cloudSync.EnqueueChangedItemAsync(publishable, configuration));
    }

    private Task HandleEnqueueResultAsync(ClipboardCloudSyncResult result)
    {
        if (result.WasSkipped) { return Task.CompletedTask; }
        CloudSyncStatus = result.Message;
        if (!result.Success || _isShuttingDown) { return Task.CompletedTask; }
        _uploadRequested = true;
        _uploadTask ??= UploadPendingAsync();
        return Task.CompletedTask;
    }

    private async Task UploadPendingAsync()
    {
        await Task.Yield(); // Assign _uploadTask before a skipped upload can complete.
        try
        {
            while (_uploadRequested && !_isShuttingDown)
            {
                _uploadRequested = false;
                await _cloudSync.UploadPendingAsync(ApplyCloudSyncResult);
            }
        }
        finally { _uploadTask = null; }
    }

    private void ApplyCloudSyncResult(ClipboardCloudSyncResult result)
    {
        if (_isShuttingDown) { return; }
        if (result.WasSkipped)
        {
            return;
        }

        CloudSyncStatus = result.Message;
        if (!result.Success || result.Batch is null || !_persistenceWritable) { return; }
        var merged = _cloudSync.MergeRemote(_items, result.Batch, _localDeletedForSync);
        _items = merged.ToList();
        SortItems();
        Prune();
        RebuildFilteredItems();
        PersistCurrent(acknowledge: result.Batch);
    }

    private static bool SnapshotsEqual(IReadOnlyList<ClipboardHistoryItem> left, IReadOnlyList<ClipboardHistoryItem> right)
    {
        return left.Count == right.Count && left.OrderBy(item => item.Id).SequenceEqual(right.OrderBy(item => item.Id));
    }

    private void ScheduleFilter()
    {
        var delayMilliseconds = (int)(_preferences.SearchInputDelay * 1_000);
        _filterDebouncer.Schedule(TimeSpan.FromMilliseconds(delayMilliseconds), RebuildFilteredItems);
    }

    private void EnsureFilterIsCurrent()
    {
        if (_appliedQuery == Query && _appliedFilter == Filter && _appliedLimit == _visibleLimit)
        {
            return;
        }

        _filterDebouncer.Cancel();
        _filterRevision += 1;
        var revision = _filterRevision;
        var term = Query.Trim();
        var matches = FilterItems(_items, term, Filter, _visibleLimit);
        ApplyFilteredItems(matches, Query, Filter, revision);
    }

    private void RebuildFilteredItems()
    {
        var term = Query.Trim();
        var requestedQuery = Query;
        var requestedFilter = Filter;
        var snapshot = _items.ToList();
        _filterRevision += 1;
        var revision = _filterRevision;

        var limit = _visibleLimit;
        if (string.IsNullOrEmpty(term))
        {
            var matches = FilterItems(snapshot, term, requestedFilter, limit);
            ApplyFilteredItems(matches, requestedQuery, requestedFilter, revision);
            return;
        }

        _ = Task.Run(() => FilterItems(snapshot, term, requestedFilter, limit))
            .ContinueWith(task =>
            {
                if (task.IsCompletedSuccessfully)
                {
                    ApplyFilteredItems(task.Result, requestedQuery, requestedFilter, revision);
                }
            }, TaskScheduler.FromCurrentSynchronizationContext());
    }

    private void ApplyFilteredItems(
        HistoryPage<ClipboardHistoryItem> page,
        string requestedQuery,
        ClipboardFilter requestedFilter,
        int revision)
    {
        if (revision != _filterRevision || Query != requestedQuery || Filter != requestedFilter)
        {
            return;
        }

        var selectedId = _appliedQuery == requestedQuery && _appliedFilter == requestedFilter
            ? _filteredItems.ElementAtOrDefault(SelectedIndex)?.Id : null;
        _filteredItems = page.Items.ToList();
        _totalMatches = page.TotalMatches;
        _appliedLimit = _visibleLimit;
        _appliedQuery = requestedQuery;
        _appliedFilter = requestedFilter;
        var retainedIndex = _filteredItems.FindIndex(item => item.Id == selectedId);
        var nextSelectedIndex = retainedIndex >= 0 ? retainedIndex : Math.Max(0, Math.Min(SelectedIndex, _filteredItems.Count - 1));
        RaisePropertyChanged(nameof(FilteredItems));
        // WPF may clear selection synchronously when ItemsSource changes.
        SelectedIndex = nextSelectedIndex;
        RaisePropertyChanged(nameof(TotalMatches));
        RaisePropertyChanged(nameof(HasMore));
        RaisePropertyChanged(nameof(PageDescription));
    }

    private static HistoryPage<ClipboardHistoryItem> FilterItems(
        IReadOnlyList<ClipboardHistoryItem> items,
        string term,
        ClipboardFilter filter,
        int limit)
    {
        return HistoryPage<ClipboardHistoryItem>.Select(items, limit, item =>
        {
            var matchesType = filter == ClipboardFilter.All
                || (filter == ClipboardFilter.Pinned ? item.IsPinned : item.Kind.ToString() == filter.ToString());
            return matchesType && (string.IsNullOrEmpty(term)
                || item.DisplayText.Contains(term, StringComparison.OrdinalIgnoreCase)
                || (item.SourceApplication?.Contains(term, StringComparison.OrdinalIgnoreCase) ?? false));
        });
    }

    private static string? ForegroundProcessName()
    {
        try
        {
            var hwnd = NativeMethods.GetForegroundWindow();
            _ = NativeMethods.GetWindowThreadProcessId(hwnd, out var processId);
            using var process = System.Diagnostics.Process.GetProcessById((int)processId);
            return process.ProcessName;
        }
        catch
        {
            return null;
        }
    }

    private static byte[]? EncodePng(BitmapSource image)
    {
        var encoder = new PngBitmapEncoder();
        encoder.Frames.Add(BitmapFrame.Create(image));
        using var stream = new MemoryStream();
        encoder.Save(stream);
        return stream.ToArray();
    }

    private static BitmapSource DecodeImage(byte[] png)
    {
        using var stream = new MemoryStream(png);
        var decoder = new PngBitmapDecoder(
            stream,
            BitmapCreateOptions.PreservePixelFormat,
            BitmapCacheOption.OnLoad);
        return decoder.Frames[0];
    }

    private static string Hash(IReadOnlyList<string> parts)
    {
        return Hash(string.Join("\0", parts));
    }

    private static string Hash(byte[] data)
    {
        return Convert.ToHexString(SHA256.HashData(data)).ToLowerInvariant();
    }

    private static string Hash(string value)
    {
        return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(value))).ToLowerInvariant();
    }

    private static bool TrySetClipboard(Action write)
    {
        try
        {
            write();
            return true;
        }
        catch
        {
            // Transient clipboard lock contention must never crash the panel.
            return false;
        }
    }
}


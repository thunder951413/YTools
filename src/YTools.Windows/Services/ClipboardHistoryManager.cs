    public ClipboardHistoryManager(AppPreferences preferences, ClipboardMonitor monitor)
    {
        _preferences = preferences;
        _monitor = monitor;
        _dispatcher = Dispatcher.CurrentDispatcher;
        _cloudSync = new ClipboardCloudSyncService(preferences);
        _monitor.Changed += OnClipboardChanged;

        TrackLocalWork(LoadAsync());
        _preferenceChanged = (_, args) =>
        {
            switch (args.PropertyName)
            {
                case nameof(AppPreferences.ClipboardRetentionDays):
                case nameof(AppPreferences.ClipboardMaximumItems):
                    PruneAndPersist();
                    break;
                case nameof(AppPreferences.SearchInputDelay):
                    ScheduleFilter();
                    break;
                case nameof(AppPreferences.ClipboardCloudSyncEnabled):
                case nameof(AppPreferences.ClipboardCloudSyncFolder):
                case nameof(AppPreferences.ClipboardCloudSyncIntervalMinutes):
                    if (_storageReady)
                    {
                        StartCloudSync();
                    }

                    break;
            }
        };
        preferences.PropertyChanged += _preferenceChanged;
    }

